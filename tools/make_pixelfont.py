#!/usr/bin/env python3
"""Bakes the Pixel theme's font: Pixelify Sans (SIL OFL, tools/fonts/) at 10, 12 and 16 px with no
anti-aliasing, into romfs/pixelfont.png (white masks, alpha = the glyph) and source/core/pixelfont.c
(the metrics). Run from the repository root; needs Pillow.

What the font lacks (the button glyphs U+E000.., arrows) is drawn by screen.c from the system font.
"""
from PIL import Image, ImageDraw, ImageFont
from fontTools.ttLib import TTFont

FONT = "tools/fonts/PixelifySans.ttf"
SIZES = [10, 12, 16]
EXTRA = [0x2026, 0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x20AC, 0x2039, 0x203A, 0x2022]
ATLAS_W = 256

cmap = TTFont(FONT).getBestCmap()
codes = [c for c in list(range(0x20, 0x7F)) + list(range(0xA1, 0x100)) + EXTRA if c in cmap]

glyphs = {}   # size -> list of dict
placed = []   # (size, glyph dict, image)
for size in SIZES:
    font = ImageFont.truetype(FONT, size)
    ascent, descent = font.getmetrics()
    line = ascent + descent
    entries = []
    for code in codes:
        ch = chr(code)
        advance = int(round(font.getlength(ch)))
        pad = size
        canvas = Image.new("L", (advance + 2 * pad + size, line + 2 * pad), 0)
        d = ImageDraw.Draw(canvas)
        d.fontmode = "1"
        d.text((pad, pad + ascent), ch, font=font, fill=255, anchor="ls")
        box = canvas.getbbox()
        if box is None:
            entries.append({"code": code, "w": 0, "h": 0, "xoff": 0, "yoff": 0, "adv": advance})
            continue
        crop = canvas.crop(box)
        entries.append({"code": code, "w": crop.width, "h": crop.height, "xoff": box[0] - pad, "yoff": box[1] - pad,
                        "adv": advance, "img": crop})
    # At small sizes the acute accent of i lands where its dot is, and "i" and "i" with an accent look
    # the same: build it from the dotless i plus the accent taken from u/ú.
    if 0x131 in cmap:
        def render(code):
            pad = size
            canvas = Image.new("L", (int(round(font.getlength(chr(code)))) + 2 * pad + size, line + 2 * pad), 0)
            d = ImageDraw.Draw(canvas)
            d.fontmode = "1"
            d.text((pad, pad + ascent), chr(code), font=font, fill=255, anchor="ls")
            return canvas, pad
        u, pad = render(ord("u"))
        uacute, _ = render(0xFA)
        dotless, _ = render(0x131)
        accent = Image.new("L", u.size, 0)
        accent.putdata([255 if a and not b else 0 for a, b in zip(uacute.getdata(), u.getdata())])
        abox = accent.getbbox()
        dbox = dotless.getbbox()
        if abox and dbox:
            acrop = accent.crop(abox)
            dx = (dbox[0] + dbox[2] - acrop.width) // 2
            dotless.paste(acrop, (dx, abox[1]), acrop)
            box = dotless.getbbox()
            crop = dotless.crop(box)
            for e in entries:
                if e["code"] == 0xED:
                    e.update({"w": crop.width, "h": crop.height, "xoff": box[0] - pad, "yoff": box[1] - pad, "img": crop})
    glyphs[size] = {"ascent": ascent, "line": line, "entries": entries}

# Shelf packing, 1 px between glyphs.
x = y = rowh = 0
for size in SIZES:
    for g in glyphs[size]["entries"]:
        if g["w"] == 0:
            g["x"] = g["y"] = 0
            continue
        if x + g["w"] + 1 > ATLAS_W:
            x = 0
            y += rowh + 1
            rowh = 0
        g["x"], g["y"] = x, y
        x += g["w"] + 1
        rowh = max(rowh, g["h"])
height = 1
while height < y + rowh + 1:
    height *= 2

atlas = Image.new("RGBA", (ATLAS_W, height), (255, 255, 255, 0))
for size in SIZES:
    for g in glyphs[size]["entries"]:
        if g["w"]:
            mask = g["img"].point(lambda v: 255 if v else 0)
            white = Image.new("RGBA", mask.size, (255, 255, 255, 255))
            white.putalpha(mask)
            atlas.paste(white, (g["x"], g["y"]))
atlas.save("romfs/pixelfont.png")

with open("source/core/pixelfont.c", "w") as f:
    f.write("// Generated by tools/make_pixelfont.py from Pixelify Sans (SIL OFL 1.1): do not edit.\n")
    f.write('#include "pixelfont.h"\n\n')
    f.write("#define PIXELFONT_ATLAS_W %d\n#define PIXELFONT_ATLAS_H %d\n\n" % (ATLAS_W, height))
    for size in SIZES:
        f.write("static const pixelfont_glyph glyphs%d[] = {\n" % size)
        for g in glyphs[size]["entries"]:
            f.write("    {0x%04X, %d, %d, %d, %d, %d, %d, %d},\n" % (g["code"], g["x"], g["y"], g["w"], g["h"], g["xoff"], g["yoff"], g["adv"]))
        f.write("};\n\n")
    f.write("const pixelfont_size pixelfont_sizes[PIXELFONT_SIZE_COUNT] = {\n")
    for size in SIZES:
        f.write("    {%d, %d, %d, sizeof(glyphs%d) / sizeof(*glyphs%d), glyphs%d},\n" % (size, glyphs[size]["line"], glyphs[size]["ascent"], size, size, size))
    f.write("};\n\nconst unsigned pixelfont_atlas_width = PIXELFONT_ATLAS_W;\nconst unsigned pixelfont_atlas_height = PIXELFONT_ATLAS_H;\n")
print("glyphs", len(codes), "atlas", ATLAS_W, height, {s: (glyphs[s]["line"], glyphs[s]["ascent"]) for s in SIZES})
