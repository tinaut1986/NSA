#!/usr/bin/env python3
"""Builds romfs/icons16.png, romfs/icons32.png and source/core/icons.h from
Tabler Icons (MIT), and NSA's own icons in tools/icons/<name>.svg (drawn on
Tabler's 24 px grid with 2 px strokes, so they match).

Renders each icon in tools/icons.txt with headless Chrome and the Tabler
webfont, then turns it into a white mask whose alpha is the ink. One atlas per
size the UI draws icons at (16 px cells for rows and buttons, 32 px for big
tiles), so lines land on whole pixels instead of being scaled away. The UI
tints the mask with the theme's colours (screen_draw_icon).

Run it after editing tools/icons.txt; both outputs are committed:
    python3 tools/make_icons.py
"""
import pathlib
import subprocess
import tempfile

from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent
TABLER = "https://cdn.jsdelivr.net/npm/@tabler/icons-webfont@3.19.0/dist/tabler-icons.min.css"
SIZES = [16, 32]   # Cell sizes; the glyph fills the cell (Tabler pads its own).
COLUMNS = 16

names = [line.strip() for line in (ROOT / "tools/icons.txt").read_text().splitlines()
         if line.strip() and not line.startswith("#")]
rows = (len(names) + COLUMNS - 1) // COLUMNS


def glyph(i, n, cell):
    place = f"position:absolute;left:{(i % COLUMNS) * cell}px;top:{(i // COLUMNS) * cell}px;width:{cell}px;height:{cell}px"
    own = ROOT / "tools/icons" / f"{n}.svg"
    if own.exists():
        svg = own.read_text().strip().replace("<svg ", f'<svg width="{cell}" height="{cell}" ', 1)
        return f'<div style="{place}">{svg}</div>'
    return f'<i class="ti ti-{n}" style="{place};font-size:{cell}px;line-height:{cell}px;text-align:center"></i>'


def render(cell):
    width, height = COLUMNS * cell, rows * cell
    cells = "".join(glyph(i, n, cell) for i, n in enumerate(names))
    html = (f'<!doctype html><html><head><link rel="stylesheet" href="{TABLER}"></head>'
            f'<body style="margin:0;background:#fff;color:#000;width:{width}px;height:{height}px;position:relative;'
            f'-webkit-font-smoothing:antialiased">{cells}</body></html>')

    with tempfile.TemporaryDirectory() as tmp:
        page = pathlib.Path(tmp) / "icons.html"
        shot = pathlib.Path(tmp) / "icons.png"
        page.write_text(html)
        # Grayscale antialiasing: subpixel colour fringes would turn into noise in the mask.
        subprocess.run(["google-chrome", "--headless=new", "--disable-gpu", "--hide-scrollbars",
                        "--disable-lcd-text", "--force-device-scale-factor=1", "--virtual-time-budget=8000",
                        f"--window-size={width},{height}", f"--screenshot={shot}", page.as_uri()],
                       check=True, capture_output=True)
        gray = Image.open(shot).convert("L").crop((0, 0, width, height))

    mask = Image.new("RGBA", (width, height), (255, 255, 255, 0))
    mask.putalpha(gray.point(lambda v: 255 - v))
    mask.save(ROOT / f"romfs/icons{cell}.png")
    return width, height


sizes = [render(cell) for cell in SIZES]

header = ["#pragma once", "", "// Generated by tools/make_icons.py from tools/icons.txt. Do not edit.", "",
          f"#define ICON_COLUMNS {COLUMNS}", "", "typedef enum {"]
header += [f"    ICON_{n.upper().replace('-', '_')}," for n in names]
header += ["    ICON_COUNT", "} icon_id;", ""]
(ROOT / "source/core/icons.h").write_text("\n".join(header))
print(f"{len(names)} icons, " + ", ".join(f"{w}x{h}" for w, h in sizes))
