#!/usr/bin/env python3
"""Bakes the font for Simplified Chinese: Noto Sans CJK SC (SIL OFL 1.1) into romfs/hanfont.png (white
masks, alpha = the glyph, anti-aliased) and source/core/hanfont.c (the metrics).

Why: the console draws text with its own shared font, which on a European, American or Japanese console
is the Japanese character set, so about a quarter of Simplified Chinese is boxes there. While Simplified
Chinese is the language, screen.c draws every character of this font from the atlas instead.

Which characters: every CJK one (U+3000..U+9FFF, U+FF00..U+FFEF) that source/core/i18n_zh.c uses, so run this
again after changing that table (tools/check_i18n.py does not know about it). One size, drawn scaled like the
system font: a line of 30 units, the ideographs 26 wide.

The font file is not in the repository (16 MB); download it once:
  https://github.com/notofonts/noto-cjk/raw/main/Sans/OTF/SimplifiedChinese/NotoSansCJKsc-Regular.otf
and pass its path, or put it in tools/fonts/. Run from the repository root; needs Pillow.
"""
import re
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

FONT = sys.argv[1] if len(sys.argv) > 1 else "tools/fonts/NotoSansCJKsc-Regular.otf"
TABLE = "source/core/i18n_zh.c"
EM = 26           # Size of an ideograph, in atlas pixels.
LINE = 30         # The line feed screen.c scales by: the system font's.
CELL = EM + 4     # Room for a glyph and a margin, so linear filtering does not bleed one into the next.
ATLAS_W = 512


def cjk(code):
    return 0x3000 <= code <= 0x9FFF or 0xFF00 <= code <= 0xFFEF


text = Path(TABLE).read_text(encoding="utf-8")
codes = sorted({ord(c) for c in text if cjk(ord(c))})

font = ImageFont.truetype(FONT, EM)
ascent, descent = font.getmetrics()

per_row = ATLAS_W // CELL
rows = (len(codes) + per_row - 1) // per_row
height = rows * CELL
atlas = Image.new("RGBA", (ATLAS_W, height), (255, 255, 255, 0))

entries = []
for n, code in enumerate(codes):
    ch = chr(code)
    cx, cy = (n % per_row) * CELL, (n // per_row) * CELL
    canvas = Image.new("L", (CELL * 2, CELL * 2), 0)
    ImageDraw.Draw(canvas).text((CELL // 2, CELL // 2 + ascent), ch, font=font, fill=255, anchor="ls")
    box = canvas.getbbox()
    advance = EM
    if box is None:
        entries.append((code, 0, 0, 0, 0, 0, 0, advance))
        continue
    crop = canvas.crop(box)
    mask = Image.new("RGBA", crop.size, (255, 255, 255, 0))
    mask.putalpha(crop)
    atlas.paste(mask, (cx + 1, cy + 1))
    # Where the glyph sits: from the pen to its left, and from the baseline to its top (negative: above it).
    entries.append((code, cx + 1, cy + 1, crop.width, crop.height, box[0] - CELL // 2, box[1] - (CELL // 2 + ascent), advance))

# White, with 16 levels of transparency: a 4-bit palette PNG (stb_image reads it as RGBA), a third of the size.
levels = atlas.getchannel("A").point(lambda v: round(v / 17))
packed = Image.new("P", atlas.size, 0)
packed.putdata(list(levels.tobytes()))
packed.putpalette([255, 255, 255] * 16 + [0] * (768 - 48))
packed.info["transparency"] = bytes(i * 17 for i in range(16))
packed.save("romfs/hanfont.png", optimize=True, bits=4)

with open("source/core/hanfont.c", "w", newline="\n") as f:
    f.write("// Generated by tools/make_hanfont.py from Noto Sans CJK SC (SIL OFL 1.1): do not edit.\n")
    f.write('#include "hanfont.h"\n\n')
    f.write("const hanfont_glyph hanfont_glyphs[] = {\n")
    for e in entries:
        f.write("    {0x%04X, %d, %d, %d, %d, %d, %d, %d},\n" % e)
    f.write("};\n\n")
    f.write("const unsigned hanfont_count = sizeof(hanfont_glyphs) / sizeof(*hanfont_glyphs);\n")
    f.write("const unsigned hanfont_atlas_width = %d;\nconst unsigned hanfont_atlas_height = %d;\n" % (ATLAS_W, height))
    f.write("const unsigned hanfont_line = %d;\n" % LINE)
print("glyphs", len(codes), "atlas", ATLAS_W, height, "png", Path("romfs/hanfont.png").stat().st_size, "bytes")
